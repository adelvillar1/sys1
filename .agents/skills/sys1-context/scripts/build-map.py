#!/usr/bin/env python3
"""
build-map.py — single source of truth for a docs/context fragment set (project-agnostic).

Reads `fragments.config` and the YAML-ish frontmatter of every fragment under
<repo>/<docs_dir>, then regenerates:
  1. <repo>/<docs_dir>/README.md   — the human index, grouped by category
  2. <skill_dir>/MAP.md            — source file -> fragment(s) routing/drift map

Config + repo resolution (in order):
  repo   = --repo PATH, else the nearest ancestor of cwd containing .git
  config = --config PATH, else fragments.config next to this script's skill dir,
           else <repo>/.agents/skills/*/fragments.config (first sorted match)

MAP.md is written next to whichever fragments.config was loaded, so both the
repo-embedded copy (canonical) and a global-kit copy pointed at a repo work.
No third-party deps (hand-rolled frontmatter parser over the small subset we
author). Run after editing a fragment:

    python3 .agents/skills/<proj>-context/scripts/build-map.py

Idempotent. Prints a summary + any fragment missing frontmatter (exit 1 on missing).
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

SCRIPT = Path(__file__).resolve()
EMBEDDED_SKILL_DIR = SCRIPT.parents[1]  # <repo>/.agents/skills/<proj>-context (when embedded)

MARK = "<!-- GENERATED by scripts/build-map.py — do not edit by hand; edit fragment frontmatter instead -->"


def git_root(start: Path) -> Path | None:
    cur = start.resolve()
    for candidate in (cur, *cur.parents):
        if (candidate / ".git").exists():
            return candidate
    return None


def resolve_repo(explicit: str | None) -> Path:
    if explicit:
        return Path(explicit).expanduser().resolve()
    root = git_root(Path.cwd())
    if root is not None:
        return root
    # embedded-copy fallback: the dir owning .agents/skills
    if EMBEDDED_SKILL_DIR.parent.parent.name in (".agents", ".claude", ".zcode"):
        return EMBEDDED_SKILL_DIR.parent.parent
    raise SystemExit("build-map.py: not inside a git repo; pass --repo PATH")


def resolve_config(repo: Path, explicit: str | None) -> Path:
    if explicit:
        p = Path(explicit).expanduser().resolve()
        if not p.exists():
            raise SystemExit(f"build-map.py: config not found: {p}")
        return p
    embedded = EMBEDDED_SKILL_DIR / "fragments.config"
    if embedded.exists():
        return embedded
    for base in (".agents", ".claude", ".zcode"):
        candidates = sorted((repo / base / "skills").glob("*/fragments.config")) if (repo / base / "skills").exists() else []
        if candidates:
            return candidates[0]
    raise SystemExit("build-map.py: no fragments.config found (next to script or under <repo>/.agents/skills/*/)")


def load_config(path: Path) -> dict:
    cfg = json.loads(path.read_text(encoding="utf-8"))
    cfg.setdefault("docs_dir", "docs/context")
    cfg.setdefault("categories", [])  # ordered [{"dir":..,"label":..}]
    return cfg


def parse_frontmatter(text: str) -> dict | None:
    if not text.startswith("---"):
        return None
    end = text.find("\n---", 3)
    if end == -1:
        return None
    fm: dict = {}
    key = None
    for raw in text[3:end].strip("\n").splitlines():
        line = raw.rstrip()
        if not line.strip():
            continue
        if line.startswith("  - ") or line.startswith("- "):
            if key:
                fm.setdefault(key, [])
                if isinstance(fm[key], list):
                    fm[key].append(line.split("- ", 1)[1].strip())
            continue
        if ":" in line:
            k, _, v = line.partition(":")
            key = k.strip()
            v = v.strip()
            if v in ("", "[]"):
                fm[key] = []
            elif v.startswith("[") and v.endswith("]"):
                fm[key] = [x.strip() for x in v[1:-1].split(",") if x.strip()]
            else:
                fm[key] = v
    return fm


def collect(docs: Path) -> list[dict]:
    frags = []
    for md in sorted(docs.rglob("*.md")):
        rel = md.relative_to(docs)
        if rel.name == "README.md":
            continue
        fm = parse_frontmatter(md.read_text(encoding="utf-8"))
        frags.append({
            "path": str(rel),
            "category": rel.parts[0] if len(rel.parts) > 1 else "",
            "title": (fm or {}).get("title") or md.stem,
            "status": (fm or {}).get("status", "?"),
            "sources": (fm or {}).get("sources", []) or [],
            "related": (fm or {}).get("related", []) or [],
            "has_fm": fm is not None,
        })
    return frags


def category_order(cfg: dict, frags: list[dict]) -> list[tuple[str, str]]:
    """Configured categories first (in order), then any extra dirs found, then root-level ('')."""
    order = [(c["dir"], c.get("label", c["dir"])) for c in cfg["categories"]]
    known = {d for d, _ in order}
    extras = sorted({f["category"] for f in frags if f["category"] and f["category"] not in known})
    order += [(d, d) for d in extras]
    if any(f["category"] == "" for f in frags):
        order.append(("", "Other"))
    return order


def render_readme(cfg: dict, frags: list[dict], skill: str) -> str:
    proj = cfg.get("project", "this project")
    out = [f"# {proj} — design fragments", "", MARK, "",
           "Small, focused fragments that mirror the codebase. Each declares the source files it",
           "covers (frontmatter `sources:`). Regenerate this index with",
           f"`python3 {skill}/scripts/build-map.py`.", ""]
    by_cat: dict[str, list[dict]] = {}
    for f in frags:
        by_cat.setdefault(f["category"], []).append(f)
    for cat, label in category_order(cfg, frags):
        items = by_cat.get(cat, [])
        if not items:
            continue
        out += [f"## {label}", "", "| Fragment | Status | Covers |", "|---|---|---|"]
        for f in sorted(items, key=lambda x: x["path"]):
            covers = ", ".join(Path(s).name for s in f["sources"][:4]) or "—"
            if len(f["sources"]) > 4:
                covers += ", …"
            out.append(f"| [{f['title']}]({f['path']}) | {f['status']} | {covers} |")
        out.append("")
    return "\n".join(out) + "\n"


def render_map(cfg: dict, frags: list[dict], skill: str) -> str:
    proj = cfg.get("project", "project")
    rev: dict[str, list[str]] = {}
    for f in frags:
        for s in f["sources"]:
            rev.setdefault(s, []).append(f["path"])
    out = [f"# {proj} context MAP", "", MARK, "",
           "Reverse index: **source file → the fragment(s) that document it.** Used by the",
           f"`{skill}` skill to load the right fragment when you touch a file and to detect drift.",
           "Regenerate via `scripts/build-map.py`.", "",
           "## Source file → fragment(s)", "", "| Source file | Documented in |", "|---|---|"]
    for src in sorted(rev):
        out.append(f"| `{src}` | {', '.join(sorted(set(rev[src])))} |")
    out += ["", "## Fragment → sources", "", "| Fragment | Sources |", "|---|---|"]
    for f in sorted(frags, key=lambda x: x["path"]):
        srcs = ", ".join(f"`{Path(s).name}`" for s in f["sources"]) or "_(no source files — narrative/reference)_"
        out.append(f"| `{f['path']}` | {srcs} |")
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description="Regenerate the fragment index and source->fragment MAP")
    ap.add_argument("--repo", help="repo root (default: nearest ancestor of cwd containing .git)")
    ap.add_argument("--config", help="path to fragments.config (default: next to this script, then <repo>/.agents/skills/*/)")
    args = ap.parse_args()

    repo = resolve_repo(args.repo)
    config_path = resolve_config(repo, args.config)
    cfg = load_config(config_path)
    skill_dir = config_path.parent
    skill = str(skill_dir.relative_to(repo)) if skill_dir.is_relative_to(repo) else skill_dir.name

    docs = repo / cfg["docs_dir"]
    if not docs.exists():
        print(f"docs dir not found: {docs}", file=sys.stderr)
        return 2
    frags = collect(docs)
    (docs / "README.md").write_text(render_readme(cfg, frags, skill), encoding="utf-8")
    (skill_dir / "MAP.md").write_text(render_map(cfg, frags, skill), encoding="utf-8")
    missing = [f["path"] for f in frags if not f["has_fm"]]
    n_src = len({s for f in frags for s in f["sources"]})
    print(f"✓ {len(frags)} fragments · {n_src} mapped source files")
    print(f"  wrote {cfg['docs_dir']}/README.md")
    print(f"  wrote {skill_dir / 'MAP.md'}")
    if missing:
        print("⚠ fragments missing frontmatter:", ", ".join(missing))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
